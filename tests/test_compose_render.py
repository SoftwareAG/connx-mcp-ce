from __future__ import annotations

from pathlib import Path

from connx_mcp import compose
from connx_mcp.environment import Environment, HostSettings

GOLDEN = Path(__file__).parent / "fixtures" / "compose"
DIGEST_1 = "softwareagcr.azurecr.io/connx-mcp-server-ce@sha256:" + "1" * 64
DIGEST_2 = "registry.example/connx@sha256:" + "2" * 64


def test_a_default_environment_renders_the_golden_file(tmp_path: Path) -> None:
    env = Environment(
        name="sales",
        directory=tmp_path / "sales",
        host=HostSettings(cdd_file="/srv/connx/sales.cdd", image_digest=DIGEST_1),
    )

    assert compose.render(compose.spec_for(env)) == (GOLDEN / "default.yml").read_text(encoding="utf-8")


def test_the_rendered_file_says_connx_mcp_ce_generates_it(tmp_path: Path) -> None:
    env = Environment(
        name="sales", directory=tmp_path / "sales", host=HostSettings(cdd_file="/srv/sales.cdd", image_digest=DIGEST_1)
    )

    lines = compose.render(compose.spec_for(env)).splitlines()

    assert lines[0] == "# Generated by connx-mcp-ce on every start: do not edit, changes are overwritten."
    assert lines[2] == "# connx-mcp-ce layers it on top and never touches it."


def test_added_host_settings_extend_the_render_input(tmp_path: Path) -> None:
    env = Environment(
        name="test_2",
        directory=tmp_path / "test_2",
        host=HostSettings(
            cdd_file='/home/a$b/My Dictionaries/test "2".cdd', image_digest=DIGEST_2, published_port=8443
        ),
    )
    spec = compose.spec_for(env)
    spec.mounts = [m for m in spec.mounts if m.target == compose.CDD_TARGET]
    spec.mounts.append(compose.Mount(source="/srv/connx/certs", target=compose.CERTS_TARGET, read_only=True))
    spec.health_start_period = 300

    assert compose.render(spec) == (GOLDEN / "extended.yml").read_text(encoding="utf-8")
